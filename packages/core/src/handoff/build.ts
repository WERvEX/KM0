const NEXT_TIER: Record<string, string | null> = { T1: "T2", T2: "T3", T3: null };
const pad = (seq: number) => String(seq).padStart(2, "0");
export const taskPath = (seq: number) => `${HANDOFF_ROOT}/tasks/${pad(seq)}.md`;
export const documentPath = (kind: DocumentKind) => `${HANDOFF_ROOT}/docs/${DOCUMENT_TEMPLATES[kind].fileName}`;

/** Sections a task should see: the ones it cites, or a sensible default for its kind of work. */
function sectionsFor(task: RoutedTask, documents: HandoffDocument[]): SectionRef[] {
  if (task.sections.length > 0) return task.sections;
  const available = new Set(documents.flatMap((doc) => doc.sections.map((section) => `${doc.kind}.${section.id}`)));
  const defaults =
    task.features.kind === "docs"
      ? ["prd.background", "prd.functional", "brief.goal", "brief.scope"]
      : ["tech_design.architecture", "tech_design.modules", "brief.scope", "brief.approach"];
  return defaults
    .filter((ref) => available.has(ref))
    .map((ref) => {
      const [kind, sectionId] = ref.split(".") as [DocumentKind, string];
      return { kind, sectionId };
    });
}

/** Decisions a task should see: the ones it cites, or the technology choices and delivery form. */
function decisionsFor(task: RoutedTask, decisions: Decision[]): Decision[] {
  if (task.decisionKeys.length > 0) return decisions.filter((decision) => task.decisionKeys.includes(decision.key));
  const fallback = new Set(["scale", "frontend", "backend", "storage", "deployment", "brief_approach", "scope"]);
  return decisions.filter((decision) => fallback.has(decision.key));
}

function excerpts(task: RoutedTask, input: HandoffInput): string[] {
  const text = TEXT[input.language];
  const parts: string[] = [];
  let budget: number = EXCERPT_LIMITS.total;
  for (const ref of sectionsFor(task, input.documents)) {
    const doc = input.documents.find((item) => item.kind === ref.kind);
    const section = doc?.sections.find((item) => item.id === ref.sectionId);
    if (!section?.body.trim() || budget <= 0) continue;
    const limit = Math.min(EXCERPT_LIMITS.section, budget);
    const body = section.body.trim();
    const cut = body.length > limit ? `${body.slice(0, limit).trimEnd()}\n\n${text.cut(documentPath(ref.kind))}` : body;
    budget -= Math.min(body.length, limit);
    parts.push(`### ${DOCUMENT_TEMPLATES[ref.kind].title[input.language]} · ${section.title}\n\n${cut}`);
  }
  return parts;
}

export function taskPrompt(task: RoutedTask, input: HandoffInput): string {
  const text = TEXT[input.language];
  const byseq = new Map(input.plan.tasks.map((item) => [item.seq, item]));
  const list = (items: string[]) => (items.length > 0 ? items.map((item) => `- ${item}`).join("\n") : text.none);
  const decisions = decisionsFor(task, input.decisions).map((decision) => {
    const label = keyDef(decision.key)?.label[input.language] ?? decision.key;
    const why = decision.rationale ? text.because(decision.rationale) : "";
    return `${label}${text.colon}${decision.value.text}${why}`;
  });
  const quoted = excerpts(task, input);
  const rules = [
    text.ruleScope,
    text.ruleUnsure,
    task.features.hasTests ? text.ruleTests : text.ruleNoTests,
    ...[...new Set(task.features.risks)].map((risk) => text.risk[risk]),
  ];
  const sections = [
    `# ${text.task} ${pad(task.seq)}${text.colon}${task.title}`,
    `> ${text.generated(input.title, task.tier, task.model ?? text.noModel)}`,
    task.escalatedFrom ? `> ${text.escalated(task.escalatedFrom, task.tier)}` : "",
    `## ${text.goal}\n\n${task.goal}`,
    `## ${text.acceptance}\n\n${list(task.acceptance)}`,
    task.files.length > 0
      ? `## ${text.files}\n\n${list(task.files.map((file) => `\`${file}\``))}\n\n${text.filesNote}`
      : "",
    `## ${text.before}\n\n${
      task.dependsOn.length > 0
        ? `${list(task.dependsOn.map((seq) => `${text.task} ${pad(seq)}${text.colon}${byseq.get(seq)?.title ?? ""} (\`${taskPath(seq)}\`)`))}\n\n${text.beforeNote}`
        : text.none
    }`,
    decisions.length > 0 ? `## ${text.decisions}\n\n${list(decisions)}` : "",
    quoted.length > 0
      ? `## ${text.excerpts}\n\n${quoted.join("\n\n")}\n\n${input.documents.map((doc) => text.fullDoc(documentPath(doc.kind))).join(" · ")}`
      : "",
    `## ${text.rules}\n\n${list(rules)}`,
    `## ${text.done}\n\n${list([text.doneCheck, text.doneSummary])}`,
    `## ${text.escalate}\n\n${text.escalateBody(task.tier, NEXT_TIER[task.tier] ?? null)}`,
  ];
  return `${sections.filter(Boolean).join("\n\n")}\n`;
}

/** The overview every agent's project instructions file carries. */
export function projectOverview(input: HandoffInput): string {
  const text = TEXT[input.language];
  const value = (key: string) => input.decisions.find((decision) => decision.key === key)?.value.text;
  const labelled = (keys: string[]) =>
    keys.flatMap((key) => {
      const found = value(key);
      return found ? [`- ${keyDef(key)?.label[input.language] ?? key}${text.colon}${found}`] : [];
    });
  const form = labelled(["scale", "user_scale", "compliance"]);
  const stack = labelled([
    "frontend",
    "backend",
    "storage",
    "deployment",
    "auth_impl",
    "integrations",
    "brief_approach",
  ]);
  return [
    `# ${input.title}`,
    `## ${text.overview}\n\n${input.description.trim()}`,
    form.length > 0 ? `## ${text.form}\n\n${form.join("\n")}` : "",
    stack.length > 0 ? `## ${text.stack}\n\n${stack.join("\n")}` : "",
    `## ${text.workflow}\n\n${text.workflowBody.map((line) => `- ${line}`).join("\n")}`,
  ]
    .filter(Boolean)
    .join("\n\n")
    .concat("\n");
}

/** Lay out the whole package: docs, one prompt per task, tasks.json, instructions per agent and a README. */
export function buildHandoff(input: HandoffInput): HandoffPackage {
  const text = TEXT[input.language];
  const overview = projectOverview(input);
  const used = [...new Set(input.plan.tasks.map((task) => task.agent))] as AgentId[];

  const tasks: HandoffTask[] = input.plan.tasks.map((task) => {
    const path = taskPath(task.seq);
    return {
      taskId: task.id,
      seq: task.seq,
      title: task.title,
      tier: task.tier,
      agent: task.agent,
      model: task.model,
      promptPath: path,
      prompt: taskPrompt(task, input),
      command: ADAPTERS[task.agent].command(text.taskPrompt(path), task.model),
    };
  });

  const agents: HandoffAgent[] = used.map((id) => {
    const adapter = ADAPTERS[id];
    return {
      id,
      instructionsPath: adapter.instructions ? `${HANDOFF_ROOT}/agents/${adapter.instructions.packagedAs}` : null,
      howTo: adapter.howTo[input.language],
    };
  });

  const instructionFiles: HandoffFile[] = [];
  for (const id of used) {
    const instructions = ADAPTERS[id].instructions;
    const path = instructions ? `${HANDOFF_ROOT}/agents/${instructions.packagedAs}` : null;
    if (!instructions || !path || instructionFiles.some((file) => file.path === path)) continue;
    instructionFiles.push({ path, content: instructions.render(overview, input.language) });
  }

  const tasksJson = input.plan.tasks.map((task) => ({
    seq: task.seq,
    title: task.title,
    goal: task.goal,
    acceptance: task.acceptance,
    files: task.files,
    dependsOn: task.dependsOn,
    tier: task.tier,
    agent: task.agent,
    model: task.model,
    prompt: taskPath(task.seq),
  }));

  const row = (cells: string[]) => `| ${cells.map((cell) => cell.replaceAll("|", "\\|")).join(" | ")} |`;
  const readme = [
    `# ${text.readme} · ${input.title}`,
    text.readmeIntro.map((line, index) => `${index + 1}. ${line}`).join("\n"),
    [
      row([...text.tasksTable]),
      row(text.tasksTable.map(() => "---")),
      ...tasks.map((task) =>
        row([
          pad(task.seq),
          `[${task.title}](tasks/${pad(task.seq)}.md)`,
          task.tier,
          ADAPTERS[task.agent].name,
          task.model ?? "—",
          task.command ? `\`${task.command}\`` : text.paste,
        ]),
      ),
    ].join("\n"),
    `## ${text.agentsTitle}\n\n${agents
      .map((agent) => {
        const instructions = ADAPTERS[agent.id].instructions;
        const lines = [`### ${ADAPTERS[agent.id].name}`, agent.howTo];
        if (instructions && agent.instructionsPath) {
          lines.push(text.instructionsAt(agent.instructionsPath, instructions.target));
        }
        return lines.join("\n\n");
      })
      .join("\n\n")}`,
  ].join("\n\n");

  const files: HandoffFile[] = [
    { path: `${HANDOFF_ROOT}/README.md`, content: `${readme}\n` },
    ...input.documents.map((doc) => ({ path: documentPath(doc.kind), content: doc.markdown })),
    { path: `${HANDOFF_ROOT}/tasks.json`, content: `${JSON.stringify(tasksJson, null, 2)}\n` },
    ...tasks.map((task) => ({ path: task.promptPath, content: task.prompt })),
    ...instructionFiles,
  ];
  return { projectId: input.projectId, createdAt: input.createdAt, root: HANDOFF_ROOT, files, tasks, agents };
}
